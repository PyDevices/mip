# 256 / (2π) — map radians to table index without importing math.
_RAD_TO_U = 40.74366543152521
# 256 / 360 — map degrees to table index.
_DEG_TO_U = 256 / 360


def sin_cos_u(u):
    """Return ``(sin, cos)`` Q15 for unit-circle index ``u`` (any int)."""
    i = u & 255
    return _SIN_Q15[i], _SIN_Q15[(i + 64) & 255]


def sin_cos_deg(deg):
    """Return ``(sin, cos)`` Q15 for ``deg`` degrees."""
    return sin_cos_u(int(deg * _DEG_TO_U))


def sin_cos_rad(rad):
    """Return ``(sin, cos)`` Q15 for ``rad`` radians."""
    return sin_cos_u(int(rad * _RAD_TO_U))


def rotate_q15(px, py, cx, cy, sin_a, cos_a):
    """Rotate ``(px, py)`` about ``(cx, cy)`` with Q15 ``sin_a``/``cos_a``."""
    dx = px - cx
    dy = py - cy
    rx = cx + ((dx * cos_a - dy * sin_a) >> 15)
    ry = cy + ((dx * sin_a + dy * cos_a) >> 15)
    return rx, ry
